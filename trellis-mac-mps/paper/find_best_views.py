"""
Generates each object's 3D output ONCE (expensive), then cheaply renders a grid of candidate
camera angles for each so the best visual match to the input photo's viewpoint can be picked by
inspection -- different objects' generated assets don't share a consistent canonical orientation,
so no single fixed (yaw, pitch) matches every input's framing.

CONFIRMED BUG, applies to every render in this pipeline (not new-script-specific -- the same
orientation issue appears in outputs/preview_gaussian_color.png, generated by an earlier
session's quick_preview.py): renders come out rotated 180 degrees ("upside down" -- point-
reflected, not mirrored) relative to the object's actual orientation. Confirmed directly: T.png's
render only reveals its actual shape (a capital letter "T", matching the filename) after a 180
degree correction; before correction it looks like a plausible-but-wrong "vine-cap-on-top,
fence-on-bottom" shape. Root cause not yet isolated (likely a world-up-vector or coordinate-
convention mismatch somewhere in render_utils.py / utils3d); NOT fixed in the shared
render_utils.py itself (would need to verify it doesn't break other, already-verified callers)
-- fixed here as a local post-process (rotate every rendered frame 180 degrees) in this script and
its siblings (generate_teaser.py, generate_turntables.py) instead.
"""
import os, sys
os.environ['SPARSE_BACKEND'] = 'pytorch'
os.environ['ATTN_BACKEND'] = 'sdpa'
sys.path.insert(0, '/Users/vinayak/Downloads/TRELLIS-main')
os.chdir('/Users/vinayak/Downloads/TRELLIS-main')

import torch
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from trellis.pipelines import TrellisImageTo3DPipeline
from trellis.utils import render_utils

device = 'mps' if torch.backends.mps.is_available() else 'cpu'
out_dir = "/Users/vinayak/Downloads/TRELLIS-main/paper/figures"
os.makedirs(out_dir, exist_ok=True)

pipeline = TrellisImageTo3DPipeline.from_pretrained("microsoft/TRELLIS-image-large")
pipeline.to(device)

OBJECTS = {
    'T': 'assets/example_image/T.png',
    'vase': 'assets/example_image/object2_vase.png',
    'dragon': 'assets/example_image/typical_creature_dragon.png',
    'biplane': 'assets/example_image/typical_vehicle_biplane.png',
}

YAW_DEGS = [0, 45, 90, 135, 180, 225, 270, 315]
PITCH_DEG = 15

font = None
try:
    font = ImageFont.truetype('/System/Library/Fonts/Helvetica.ttc', 18)
except Exception:
    font = ImageFont.load_default()


def fix_orientation(frame_uint8):
    """Corrects the confirmed 180-degree render bug -- point-reflection, i.e. rot90 twice."""
    return np.rot90(frame_uint8, 2).copy()


for name, path in OBJECTS.items():
    print(f"generating {name} ...", flush=True)
    image = Image.open(path)
    with torch.no_grad():
        out = pipeline.run(image, seed=1, formats=['gaussian'])
    gaussian = out['gaussian'][0]

    yaws = [np.deg2rad(y) for y in YAW_DEGS]
    pitches = [np.deg2rad(PITCH_DEG)] * len(yaws)
    ex_in, in_intr = render_utils.yaw_pitch_r_fov_to_extrinsics_intrinsics(yaws, pitches, 2, 40, device=gaussian.get_xyz.device)
    frames = render_utils.render_frames(gaussian, ex_in, in_intr, options={'resolution': 320})

    tile_w, tile_h, label_h = 320, 320, 24
    grid = Image.new('RGB', (len(YAW_DEGS) * tile_w, tile_h + label_h), '#ffffff')
    draw = ImageDraw.Draw(grid)
    for i, yaw_deg in enumerate(YAW_DEGS):
        corrected = fix_orientation(frames['color'][i].astype(np.uint8))
        tile = Image.fromarray(corrected)
        grid.paste(tile, (i * tile_w, label_h))
        draw.text((i * tile_w + 8, 2), f"yaw={yaw_deg}", fill='#111111', font=font)
    grid.save(os.path.join(out_dir, f'_scan_{name}.png'))
    print(f"  wrote _scan_{name}.png", flush=True)
    torch.mps.empty_cache()

print("done -- inspect paper/figures/_scan_*.png (orientation-corrected) and pick the best yaw per object")
